// while loop 
// use when we have to do some task repeatedly.

//Synatx: 
// while(condition){
    //code
//  }

//Print numbers from 1 to 10 using while loop

class whileLoop{
    public static void main(String[] args){

        int i = 1;
        while(i<=10){
            System.out.println(i);
            i++;
        }
        System.out.println("1 to 10 number printed.");
    }
}
