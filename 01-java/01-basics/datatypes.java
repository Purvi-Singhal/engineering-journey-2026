

public class datatypes {
    public static void main(String args[]){
        byte m = 8;  //store 256 numbers 
        System.out.println(m);
        char ch='P';  //store every single character
        System.out.println(ch);
        boolean var = true; //store two types of value either true or false.
        System.out.println(var);
        float price = 10.5f;
        System.out.println(price);
        int number = 25;
        //long number2 = 1234567890; //store large numbers
        //double number3 = 123.4567890; //store large decimal numbers
        System.out.println(number);
        short n = 240; //store 65536 numbers
        System.out.println(n);


        //sum of a and b

        int a = 10;
        int b = 20;
        int sum = a+b;
        System.out.println(sum);

    }
}
